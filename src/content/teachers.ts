/** Педагог для показа: при разработке — вместе с черновиком (демо), на продакшене — только подтверждённое. */
export function visibleTeacher(t: SiteTeacher, production = process.env.NODE_ENV === "production") {
  if (production || !t.draft) return { ...t, draft: undefined };
  return {
    ...t,
    stats: [...t.stats, ...(t.draft.stats ?? [])],
    tags: [...t.tags, ...(t.draft.tags ?? [])],
    about: [t.about, t.draft.about].filter(Boolean).join(" "),
    draft: undefined,
  };
}
