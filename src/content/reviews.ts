/** Какие отзывы показывать: настоящие всегда, примеры — только не на продакшене. */
export function visibleReviews(all: readonly SiteReview[] = SITE_REVIEWS, production = process.env.NODE_ENV === "production") {
  return all.filter((r) => !r.example || !production);
}
